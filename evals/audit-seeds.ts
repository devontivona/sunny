import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ALL_CASES } from './cases/index.js';
import { historyTier, type EvalCase } from './types.js';

/**
 * Seed/fixture audit (seed-audit policy, 2026-07): `npm run eval:audit`. FREE — no
 * model calls. For every case that seeds history, reports what the graded turn will
 * actually run against, so eval results are always read against their history:
 *
 * - SHAPE — per seeded assistant turn: sends / scratch / tool calls. A pristine turn
 *   (one send, no tool call, no scratch) for an outcome that would require a tool
 *   ("Timer set…") is UNREALISTIC — production turns never look like that.
 * - DUAL-CHANNEL — scratch containing user-addressed language (second-person
 *   heuristic, same as the `scratch-not-second-person` grader). In a `poisoned`
 *   case that's the point (it must be deliberate + tagged); anywhere else it's
 *   contamination that normalizes the miss in-context.
 *
 * Output: evals/seed-audit.md (committed) + stdout.
 */

interface TurnReport {
  index: number;
  source: 'conversation' | 'fixture';
  sends: number;
  toolCalls: string[];
  scratchChars: number;
  scratchSecondPersonHits: number;
  dualChannel: boolean;
  pristine: boolean;
}

function secondPersonHits(text: string): number {
  return text.match(/\byou(?:r|'re|'ve|'ll|'d)?\b/gi)?.length ?? 0;
}

/** Same threshold as the `scratch-not-second-person` grader. */
function isUserAddressed(scratch: string): boolean {
  const hits = secondPersonHits(scratch);
  return hits >= 2 && hits / scratch.split(/\s+/).length > 0.02;
}

function auditCase(c: EvalCase): TurnReport[] {
  const reports: TurnReport[] = [];
  let i = 0;

  for (const seed of c.setup?.conversation ?? []) {
    i += 1;
    if (seed.role !== 'assistant') continue;
    const sends = seed.sends ?? (seed.text ? [seed.text] : []);
    const scratch = seed.scratch ?? '';
    reports.push({
      index: i,
      source: 'conversation',
      sends: sends.length,
      toolCalls: sends.map(() => 'send_message'),
      scratchChars: scratch.length,
      scratchSecondPersonHits: secondPersonHits(scratch),
      dualChannel: scratch.length > 0 && isUserAddressed(scratch),
      pristine: sends.length === 1 && !scratch,
    });
  }

  for (const turn of c.setup?.fixtureTurns ?? []) {
    i += 1;
    if (turn.role !== 'assistant') continue;
    const payload = turn.payload as
      | { parts?: Array<{ type: string; text?: string }> }
      | undefined;
    const parts = payload?.parts ?? [];
    const toolCalls = parts
      .filter((p) => p.type.startsWith('tool-'))
      .map((p) => p.type.slice('tool-'.length));
    const scratch = parts
      .filter((p) => p.type === 'text')
      .map((p) => p.text ?? '')
      .join('\n')
      .trim();
    const sends = toolCalls.filter((t) => t === 'send_message').length;
    reports.push({
      index: i,
      source: 'fixture',
      sends,
      toolCalls,
      scratchChars: scratch.length,
      scratchSecondPersonHits: secondPersonHits(scratch),
      dualChannel: scratch.length > 0 && isUserAddressed(scratch),
      pristine: sends === 1 && toolCalls.length === 1 && !scratch,
    });
  }

  return reports;
}

const lines: string[] = [
  '# Seed / fixture audit',
  '',
  `Generated by \`npm run eval:audit\` over ${ALL_CASES.length} cases. Regenerate after`,
  'changing any case seeding. Cases with no seeded history (`live`) are listed last.',
  '',
  '| Case | Tier | Seeded assistant turns | Dual-channel scratch | Pristine turns |',
  '|---|---|---|---|---|',
];
const liveCases: string[] = [];
let flagged = 0;

for (const c of ALL_CASES) {
  const tier = historyTier(c);
  const turns = auditCase(c);
  if (tier === 'live' && turns.length === 0) {
    liveCases.push(c.name);
    continue;
  }
  const dual = turns.filter((t) => t.dualChannel);
  const pristine = turns.filter((t) => t.pristine);
  // Dual-channel scratch outside a deliberately-poisoned case is contamination.
  // Pristine (tool-free single-send, no-scratch) turns are informational: fine for
  // smalltalk seeds, unrealistic for seeds whose text claims an action ("Timer
  // set…") — that judgment needs a human eye, so it's a column, not a flag.
  const dualBad = dual.length > 0 && tier !== 'seeded-poisoned';
  if (dualBad) flagged += 1;
  const detail = (n: number, bad: boolean) => (n === 0 ? '0' : bad ? `**${n}** ⚠️` : `${n}`);
  lines.push(
    `| ${c.name} | ${tier} | ${turns.length} | ${detail(dual.length, dualBad)} | ${pristine.length} |`,
  );
}

lines.push(
  '',
  `**${flagged}** case(s) flagged (⚠️ = dual-channel scratch outside a poisoned case).`,
  'Review the pristine column by hand: tool-free single-send seeds are fine for pure',
  'conversation, unrealistic when the send text claims an action a real turn would',
  'have made a tool call for.',
  '',
  `## Live-history cases (${liveCases.length}) — nothing seeded`,
  '',
  ...liveCases.map((n) => `- ${n}`),
  '',
);

const report = lines.join('\n');
console.log(report);
const out = join(process.cwd(), 'evals', 'seed-audit.md');
writeFileSync(out, report);
console.log(`\n→ ${out}`);
